-- ----------------------------------------------------------------------------
-- trigger_fill_previous_properties_for_all_records: Manuell: stoesst den previous_properties-Trigger fuer alle records an (zeilenweise).
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trigger_fill_previous_properties_for_all_records()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    record_id uuid;
BEGIN
    -- Loop through all records in the table
    FOR record_id IN
        SELECT id FROM public.records
    LOOP
        -- Update the record to trigger the `fill_previous_properties` function
        UPDATE public.records
        SET previous_properties_updated_at = now() -- Update a column to trigger the function
        WHERE id = record_id;
    END LOOP;

    RAISE NOTICE 'Trigger executed for all records.';
END;
$function$;

-- ----------------------------------------------------------------------------
-- update_previous_properties_in_batches: Manuell: wie trigger_fill_previous_properties_for_all_records, in Stapeln.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_previous_properties_in_batches(p_batch_size integer DEFAULT 1000)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    batch_count INTEGER := 0;
BEGIN
    LOOP
        -- Update a batch of rows and count the number of rows updated
        WITH updated_rows AS (
            UPDATE public.records
            SET previous_properties_updated_at = now()
            WHERE id IN (
                SELECT id
                FROM public.records
                WHERE previous_properties_updated_at IS DISTINCT FROM now() -- Optional condition
                LIMIT p_batch_size
            )
            RETURNING id
        )
        SELECT COUNT(*) INTO batch_count FROM updated_rows;

        -- Exit the loop if no more rows are updated
        IF batch_count = 0 THEN
            EXIT;
        END IF;

        RAISE NOTICE 'Updated % rows in this batch', batch_count;
    END LOOP;

    RAISE NOTICE 'All rows updated successfully.';
END;
$function$;

-- ----------------------------------------------------------------------------
-- update_records_from_organizations_lose_changes: Trigger auf organizations_lose: gibt Aenderungen an Losen (Verantwortliche, Trupp) an records weiter.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_records_from_organizations_lose_changes()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    org_type text;
BEGIN
    -- Handle when responsible_organization_id is changed
    IF NEW.responsible_organization_id IS DISTINCT FROM OLD.responsible_organization_id THEN
        -- If NEW.responsible_organization_id is NULL, clear the appropriate los fields
        IF NEW.responsible_organization_id IS NULL THEN
            -- Get the old organization type to know which field to clear
            SELECT type INTO org_type
            FROM organizations
            WHERE id = OLD.organization_id;
            
            -- Clear the appropriate los field based on old organization type
            CASE org_type
                WHEN 'root' THEN
                    UPDATE records
                    SET responsible_state = NULL, responsible_provider = NULL, responsible_troop = NULL, state_los = NULL, provider_los = NULL, troop_los = NULL
                    WHERE administration_los = OLD.id;

                WHEN 'country' THEN --state
                    UPDATE records
                    SET responsible_provider = NULL, responsible_troop = NULL, provider_los = NULL, troop_los = NULL
                    WHERE state_los = OLD.id;

                WHEN 'provider' THEN
                    UPDATE records
                    SET responsible_troop = NULL, troop_los = NULL
                    WHERE provider_los = OLD.id;

                ELSE
                    -- Handle unknown organization types or do nothing
                    NULL;
            END CASE;
        ELSE
            -- Get the new organization type
            SELECT type INTO org_type
            FROM organizations
            WHERE id = NEW.organization_id;
            
            -- Update records based on new organization type
            CASE org_type
                WHEN 'root' THEN
                    UPDATE records
                    --SET administration_los = NEW.id
                    SET responsible_state = NEW.responsible_organization_id, responsible_provider = NULL, responsible_troop = NULL,
                        state_los = NULL, provider_los = NULL, troop_los = NULL
                    WHERE administration_los = OLD.id;

                WHEN 'country' THEN
                    UPDATE records
                    SET responsible_provider = NEW.responsible_organization_id, responsible_troop = NULL, provider_los = NULL, troop_los = NULL
                    WHERE state_los = OLD.id;

                WHEN 'provider' THEN
                    UPDATE records
                    SET responsible_troop = NEW.troop_id, troop_los = NULL
                    WHERE provider_los = OLD.id;

                ELSE
                    -- Handle unknown organization types or do nothing
                    NULL;
            END CASE;
        END IF;
    END IF;

    IF NEW.troop_id IS DISTINCT FROM OLD.troop_id THEN
        SELECT type INTO org_type
        FROM organizations
        WHERE id = NEW.organization_id;
        
        -- Update records based on new organization type
        CASE org_type
            WHEN 'root' THEN
                UPDATE records
                SET responsible_troop = NEW.troop_id
                WHERE administration_los = NEW.id;

            WHEN 'country' THEN
                UPDATE records
                SET responsible_troop = NEW.troop_id
                WHERE state_los = NEW.id;

            WHEN 'provider' THEN
                UPDATE records
                SET responsible_troop = NEW.troop_id
                WHERE provider_los = NEW.id;

            ELSE
                -- Handle unknown organization types or do nothing
                NULL;
        END CASE;
        
    END IF;

    RETURN NEW;
END;
$function$;

